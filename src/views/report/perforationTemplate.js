/**
 * 匹配强度：2 = 命中模板名/主别名（可靠），1 = 仅弱包含命中。
 * 调用方拿它决定「要不要为本章设边界」，避免一个弱命中把后面章节全并进来。
 */
export function matchTemplateTitleLevel(domText, tplTitle) {
  if (isCaptionText(domText)) return 0
  const a = normalizeHeadingText(domText)
  const b = normalizeHeadingText(tplTitle)
  if (!a || !b) return 0
  if (a === b) return 2
  const alias = TITLE_ALIAS[tplTitle] || []
  for (let i = 0; i < alias.length; i++) {
    const al = normalizeHeadingText(alias[i])
    if (al && (a === al || a.indexOf(al) >= 0)) return 2
  }
  // 跨文档语义同义（地质设计 → 工程设计）
  const syn = SECTION_SYNONYM[tplTitle] || []
  for (let i = 0; i < syn.length; i++) {
    const sy = normalizeHeadingText(syn[i])
    if (sy && (a === sy || a.indexOf(sy) >= 0)) return 2
  }
  // 弱包含（限制长度差，避免长句误命中短标题）
  if (a.length <= b.length + 6 && (a.indexOf(b) >= 0 || b.indexOf(a) >= 0)) return 1
  return 0
}

export function matchTemplateTitle(domText, tplTitle) {
  return matchTemplateTitleLevel(domText, tplTitle) > 0
}

/** 读/写本地记住的射孔方式（按井号或全局） */
const LS_KEY = 'editorPerforationMethod'

export function loadPerforationMethod(wbWellId) {
  try {
    const key = wbWellId ? LS_KEY + ':' + wbWellId : LS_KEY
    const v = localStorage.getItem(key) || localStorage.getItem(LS_KEY)
    if (v && PERFORATION_METHODS.indexOf(v) >= 0) return v
  } catch (e) {
    // 忽略隐私模式等异常
  }
  return ''
}

export function savePerforationMethod(method, wbWellId) {
  try {
    if (PERFORATION_METHODS.indexOf(method) < 0) return
    localStorage.setItem(LS_KEY, method)
    if (wbWellId) localStorage.setItem(LS_KEY + ':' + wbWellId, method)
  } catch (e) {
    // 忽略
  }
}
