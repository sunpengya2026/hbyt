/**
 * 标题归一化：去掉空格、全角空格、编号、以及「的/情况」等可选后缀。
 * 用于模板章节标题与正文标题的模糊匹配。
 */
export function normalizeHeadingText(s) {
  return String(s || '')
    .replace(/[\s\u3000\u00a0]+/g, '')
    .replace(/^[（(]?\s*[0-9一二三四五六七八九十]{1,3}\s*[）)]?\s*[、.．]?\s*/, '')
    .replace(/^(第[一二三四五六七八九十0-9]+[章节])\s*/, '')
    .replace(/^附图\s*[0-9]*\s*/, '')
}

/**
 * 章内小节编号剥离：「3、本区块渗透率」→「本区块渗透率」。
 *
 * ⚠️ 为什么要单独抽出来（2026-11-01）：
 *   源文档（压裂地质设计）的一级章节编号是 Word 自动编号列表（numPr numId=1 ilvl=0），
 *   POI 的 paragraph.getText() 取不到自动编号，所以 /annotation/content 返回的
 *   <h1> 只有「基本数据」而没有「一、」。normalizeHeadingText 只剥「一、」这类
 *   中文序号，对「3、」「1）」原样保留 → 模板章永远匹配不上。
 *   这里再剥一层阿拉伯数字小节号，让「3、本区块渗透率」能落到某章下做边界判断。
 */
export function stripHeadingNo(s) {
  return normalizeHeadingText(s)
    .replace(/^[0-9０-９]{1,2}\s*[、.．)）]\s*/, '')
    .replace(/^[①②③④⑤⑥⑦⑧⑨⑩]\s*/, '')
}

/**
 * 图题 / 表题判断。
 *
 * ⚠️ 必须在匹配前排除（2026-11-01）：源文档的表格标题是
 *   「表1  基础数据表」「表2  套管数据表」，正文被识别成 <h1>，
 *   归一化后含「基础数据」「套管数据」→ 会把「基础数据」章误锚到表题上，
 *   后续 DOM 切片从一个表题开始数，字数与章节全部错位。
 *   「附图1 郑58-5B-3平1井综合录井图」同理，属于附图内容而非「附图及附表」章标题。
 */
export function isCaptionText(s) {
  return /^\s*(附\s*图|附\s*表|图|表)\s*[0-9０-９一二三四五六七八九十]/.test(String(s || ''))
}

